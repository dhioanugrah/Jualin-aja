<p>Tekan <strong>Bagikan</strong> di halaman barang. Kamu bisa membagikan <strong>kartu gambar berlogo</strong> (cocok untuk status WA atau story IG), mengirim tautan lewat WhatsApp, atau menyalin tautan. Orang yang membuka tautan akan masuk ke halaman barang di web.</p>

