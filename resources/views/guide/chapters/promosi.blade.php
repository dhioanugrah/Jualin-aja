<h2>Promosi barang gratis</h2>
<ul>
    <li>Setiap penjual punya kuota <strong>{{ config('jualin.promotion_weekly_quota') }} promosi per 7 hari</strong>.</li>
    <li>Barang yang dipromosikan tampil di <strong>Barang Unggulan</strong> beranda dan teratas di katalog kategorinya selama {{ config('jualin.promotion_days') }} hari, dengan label "Unggulan".</li>
