<p>Jualin Aja ITK adalah etalase jual-beli barang bekas khusus mahasiswa Institut Teknologi Kalimantan. Semua transaksi selesai lewat COD (ketemu langsung), tidak ada pembayaran online.</p>

<h2>Daftar dengan email kampus</h2>
<ol>
    <li>Buka <a href="{{ route('register') }}">Daftar</a>, isi nama, NIM, email kampus (<strong>{{ '@'.config('jualin.email_domain') }}</strong>), nomor WhatsApp, dan password.</li>
    <li>Buka email kampus, klik tautan verifikasi. Sebelum verifikasi kamu hanya bisa melihat-lihat.</li>
    <li>Setelah verifikasi, pilih <strong>Mode Pembeli</strong> atau <strong>Mode Penjual</strong>.</li>
</ol>

<h2>Mode Pembeli dan Mode Penjual</h2>
<p>Satu akun bisa membeli dan menjual. Mode hanya mengatur tampilan supaya tidak membingungkan:</p>
<ul>
    <li><strong>Mode Pembeli</strong>: beranda, katalog, favorit, dan pesanan yang kamu ajukan.</li>
    <li><strong>Mode Penjual</strong>: Dasbor Lapak, Barang Saya, tombol <strong>+ Jual</strong>, dan booking masuk.</li>
</ul>
<p>Ganti mode kapan saja lewat tombol Pembeli/Penjual di header (laptop) atau menu <strong>Akun</strong> (HP).</p>

<h2>Lengkapi profil</h2>
<p>Di <strong>Edit Profil</strong> kamu bisa mengganti foto, nama, nomor WA, prodi, dan angkatan. Email dan NIM tidak bisa diubah. Nomor WA wajib diisi sebelum masuk Mode Penjual.</p>
<div class="tip">Nomor WA-mu tidak pernah ditampilkan sebagai teks. Orang lain hanya bisa menghubungimu lewat tombol WA yang tercatat di web.</div>
