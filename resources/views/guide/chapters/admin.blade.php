<h2>Moderasi barang</h2>
<p>Buka <strong>Panel Admin → Moderasi</strong>. Setujui barang yang layak, atau pilih <strong>Perlu Perbaikan</strong> dengan catatan yang jelas. Hanya barang Disetujui yang tampil di katalog.</p>

<h2>Titik COD</h2>
<p>Di <strong>Titik COD</strong>, tambah titik dengan area Dalam ITK atau Sekitar ITK dan tautan Google Maps. Titik yang sudah dipakai booking tidak dihapus, cukup dinonaktifkan.</p>

<h2>Iklan</h2>
<p>Di <strong>Iklan</strong>, unggah banner (16:5), pilih posisi (Beranda atas atau Sela katalog), dan atur tanggal tayang. Jumlah tayang, klik, dan CTR tercatat untuk laporan ke pengiklan. Catat pembayaran di luar sistem.</p>

<h2>Laporan</h2>
<p>Di <strong>Laporan</strong>, tinjau laporan barang dan lapak. Pilihan: <strong>Sembunyikan barang</strong>, <strong>Nonaktifkan akun</strong>, atau <strong>Abaikan</strong>. Semua laporan terbuka untuk target yang sama ditutup sekaligus, dan pelapor diberi tahu.</p>

<h2>Sengketa dan pelanggaran</h2>
<p>Di <strong>Sengketa</strong>, baca bantahan laporan "tidak datang" beserta status konfirmasi kehadiran kedua pihak. <strong>Terima bantahan</strong> mencabut pelanggaran; <strong>Tolak bantahan</strong> membuatnya tetap berlaku. Bagian "Akun perlu ditinjau" menampilkan akun yang mencapai batas pelanggaran; kamu bisa mencabut pelanggaran tertentu atau menonaktifkan akun.</p>

<h2>Membaca dashboard</h2>
<p><strong>Ringkasan</strong> menampilkan jumlah mahasiswa, barang dan booking per status, pelanggaran aktif, tayang/klik iklan, dan rata-rata masukan. <strong>Masukan</strong> berisi skor 1–5 dari pengguna untuk evaluasi uji pengguna.</p>
