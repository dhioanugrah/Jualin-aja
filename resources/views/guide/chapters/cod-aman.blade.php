<h2>Dalam ITK dan Sekitar ITK</h2>
<ul>
    <li><strong>Dalam ITK</strong> (disarankan): titik tetap yang ramai dan terang, misalnya lobi gedung kuliah, perpustakaan, masjid kampus, atau gerbang utama.</li>
    <li><strong>Sekitar ITK</strong>: titik umum di luar kampus yang dipilih admin, seperti minimarket atau kafe di sekitar Karang Joang. Setiap titik punya tautan Google Maps.</li>
</ul>
<p>Pembeli tidak bisa mengetik alamat bebas, jadi tidak ada ajakan bertemu di tempat sepi.</p>

